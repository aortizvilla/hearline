const isLang = (code: string | null): code is Lang => LANGUAGES.some((l) => l.code === code);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("uiLanguage");
    if (isLang(saved)) return saved;
  } catch {
    // storage blocked: fall back to the browser language
  }
  const browser = navigator.language.slice(0, 2);
  return isLang(browser) ? browser : "en";
}

interface I18n {
  lang: Lang;
  setLang: (lang: Lang) => void;
  /** Translate `key`, filling `{name}`-style placeholders from `vars`. */
  t: (key: Key, vars?: Record<string, string | number>) => string;
  /** A tone's label in the website language (the API's English label if unknown). */
  tone: (value: string, fallback: string) => string;
  /** A voice catalog word (description, gender, accent) in the website language. */
  catalog: (english: string | undefined) => string;
  /** A topic or subcategory name in the website language, from the translations the API
   *  sends with it (stored in the database); English if this language has none. */
  name: (english: string, labels?: Record<string, string>) => string;
  /** An episode's topic name ("briefing" episodes get the translated "Daily briefing"). */
  topicName: (episode: { topic: string; topic_label: string; topic_labels?: Record<string, string> }) => string;
}

const I18nContext = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(initialLang);

  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      localStorage.setItem("uiLanguage", lang);
    } catch {
      // storage blocked: the choice lasts until the page reloads
    }
  }, [lang]);

  const t: I18n["t"] = (key, vars) =>
    TEXT[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? ""));
  const tone: I18n["tone"] = (value, fallback) => {
    const key = `tone.${value}` as Key;
    return key in en ? TEXT[lang][key] : fallback;
  };

  const catalog: I18n["catalog"] = (english) =>
    !english || lang === "en" ? (english ?? "") : (CATALOG[lang][english] ?? english);

  const name: I18n["name"] = (english, labels) => labels?.[lang] || english;
  const topicName: I18n["topicName"] = (ep) =>
    ep.topic === "briefing" ? TEXT[lang]["topic.briefing"] : name(ep.topic_label, ep.topic_labels);

  return (
    <I18nContext.Provider value={{ lang, setLang, t, tone, catalog, name, topicName }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
